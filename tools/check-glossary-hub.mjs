import fs from 'node:fs/promises';
import path from 'node:path';
import http from 'node:http';
import {createRequire} from 'node:module';
import {fileURLToPath,pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
if(!process.env.GLOSSARY_NODE_MODULES)throw new Error('Set GLOSSARY_NODE_MODULES to bundled node_modules.');
const require=createRequire(path.join(path.resolve(process.env.GLOSSARY_NODE_MODULES),'../package.json'));
const {chromium}=require('playwright');
const out=path.join(root,'outputs/glossary-hub');await fs.mkdir(out,{recursive:true});
const server=http.createServer(async(req,res)=>{
  try {
    const file=path.resolve(root,'.'+decodeURIComponent(new URL(req.url,'http://localhost').pathname));
    if(!file.startsWith(root+path.sep)){res.writeHead(403);res.end();return;}
    const mime={'.html':'text/html; charset=utf-8','.js':'text/javascript','.css':'text/css','.png':'image/png','.svg':'image/svg+xml'}[path.extname(file)] || 'application/octet-stream';
    res.writeHead(200,{'Content-Type':mime});res.end(await fs.readFile(file));
  }catch{res.writeHead(404);res.end();}
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let browser;
try {
  browser=await chromium.launch({channel:'msedge',headless:true});
  const base=`http://127.0.0.1:${server.address().port}`;
  const errors=[];
  const page=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  await page.route('**/*',route=>route.request().url().startsWith(base)?route.continue():route.abort());
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/search-textbook.html#book-lookup');
  await page.addStyleTag({content:'html { scroll-behavior: auto !important; }'});
  const input=page.locator('#book-lookup-input');
  assert.ok(await input.isVisible());
  assert.equal(await page.locator('#glossary dt').count(),84);
  const first=page.locator('#book-lookup-results a').first();
  for(const [query,target] of [['OOV','oov'],['ann','ann'],['RAG Fusion','rag-fusion'],['Agentic RAG','agentic-rag'],['TF-IDF','tf-idf'],['bi encoder','bi-encoder'],['precision@k','precision-at-k'],['precision at k','precision-at-k'],['normalization','vector-normalisation']]){
    await input.fill(query);assert.equal(await first.getAttribute('href'),'#term-'+target,query);
  }
  await input.fill('pooling');
  assert.deepEqual(await page.locator('#book-lookup-results a').evaluateAll(es=>es.slice(0,2).map(e=>e.hash)),['#term-pooling-encoder','#term-pooling-test-collections']);
  await page.locator('#book-lookup').evaluate(e=>e.scrollIntoView({behavior:'instant',block:'start'}));
  await page.screenshot({path:path.join(out,'lookup-desktop.png')});
  await first.focus();await page.keyboard.press('Enter');
  assert.ok(await page.locator('#glossary').evaluate(e=>e.open));
  assert.equal(new URL(page.url()).hash,'#term-pooling-encoder');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'term-pooling-encoder');
  await page.goBack();assert.equal(new URL(page.url()).hash,'#book-lookup');
  await page.goForward();assert.equal(new URL(page.url()).hash,'#term-pooling-encoder');
  // Repeated current-fragment link opens a manually collapsed glossary too.
  await page.locator('#glossary').evaluate(e=>e.open=false);
  await page.locator('.term-mark[href="#term-bi-encoder"]').first().focus();await page.keyboard.press('Enter');
  assert.ok(await page.locator('#glossary').evaluate(e=>e.open));
  assert.equal(new URL(page.url()).hash,'#term-bi-encoder');
  const mark=page.locator('.term-mark[href="#term-idf"]').first();
  await mark.focus();assert.ok(await page.locator('#glossary-tip').isVisible());
  const definition=(await page.locator('#definition-idf').textContent()).trim();
  assert.equal(await mark.getAttribute('data-def'),definition);
  assert.equal(await mark.getAttribute('aria-describedby'),'glossary-tip');
  assert.ok(!(await page.locator('#glossary-tip').textContent()).includes('Read the explanation'));
  await page.screenshot({path:path.join(out,'tooltip-desktop.png')});
  await page.keyboard.press('Escape');assert.ok(await page.locator('#glossary-tip').isHidden());
  assert.equal(await mark.getAttribute('aria-describedby'),'definition-idf');
  assert.ok(await page.locator('.term-mark').evaluateAll(marks=>marks.every(m=>!(m.textContent==='RAG' && /^\s+Fusion/.test(m.nextSibling?.textContent||'')) && !(m.textContent==='IDF' && /TF-$/.test(m.previousSibling?.textContent||'')))));
  await page.goto(base+'/search-textbook.html#term-hybrid-multi-stage');
  assert.ok(await page.locator('#glossary').evaluate(e=>e.open));
  assert.equal(await page.locator('#term-hybrid-multi-stage + dd .glossary-entry-nav li').count(),2);
  await page.locator('#term-hybrid-multi-stage').evaluate(e=>e.scrollIntoView({behavior:'instant',block:'start'}));
  await page.screenshot({path:path.join(out,'entry-desktop.png')});
  await page.goto(base+'/search-textbook.html#book-lookup');
  await input.fill('retrieval');
  assert.equal(await page.locator('#book-lookup-results li').count(),20);
  await page.locator('#book-lookup-more').click();
  assert.equal(await page.locator('#book-lookup-results li').count(),40);
  await input.fill('<img src=x onerror=alert(1)>');
  assert.match(await page.locator('#book-lookup-status').textContent(),/No matching/);
  assert.equal(await page.locator('#book-lookup-results img').count(),0);
  await page.locator('#book-lookup-clear').click();
  assert.equal(await input.inputValue(),'');
  assert.equal(await page.evaluate(()=>document.activeElement.id),'book-lookup-input');
  await page.setViewportSize({width:390,height:844});
  await input.fill('pooling');
  await page.locator('#book-lookup').evaluate(e=>e.scrollIntoView({behavior:'instant',block:'start'}));
  assert.ok(await page.locator('#book-lookup').evaluate(e=>e.scrollWidth<=e.clientWidth));
  await page.screenshot({path:path.join(out,'lookup-mobile.png')});
  await page.goto(base+'/search-textbook.html#term-pooling-test-collections');
  await page.locator('#term-pooling-test-collections').evaluate(e=>e.scrollIntoView({behavior:'instant',block:'start'}));
  assert.ok(await page.locator('#glossary').evaluate(e=>e.scrollWidth<=e.clientWidth));
  await page.screenshot({path:path.join(out,'entry-mobile.png')});
  await page.setViewportSize({width:1280,height:960});
  await page.locator('#glossary').evaluate(e=>e.open=false);
  await page.emulateMedia({media:'print'});
  assert.ok(await page.locator('#definition-bm25').evaluate(e=>e.getBoundingClientRect().height>0));
  assert.ok(await page.locator('#book-lookup').isHidden());
  await page.locator('#term-bm25').evaluate(e=>e.scrollIntoView({behavior:'instant',block:'start'}));
  await page.screenshot({path:path.join(out,'glossary-print.png')});
  const noJS=await browser.newPage({javaScriptEnabled:false,viewport:{width:1280,height:960}});
  await noJS.route('**/*',route=>route.request().url().startsWith(base)?route.continue():route.abort());
  await noJS.goto(base+'/search-textbook.html#term-inverted-index');
  assert.ok(await noJS.locator('#glossary').evaluate(e=>e.open));
  assert.ok(await noJS.locator('#book-lookup').isHidden());
  await noJS.locator('#term-inverted-index').evaluate(e=>e.scrollIntoView({behavior:'instant',block:'start'}));
  await noJS.screenshot({path:path.join(out,'glossary-nojs.png')});
  assert.ok(await noJS.locator('#term-inverted-index + dd a[href="#from-analysed-tokens-to-a-term-first-map"]').count());
  const touch=await browser.newPage({hasTouch:true,isMobile:true,viewport:{width:390,height:844}});
  await touch.route('**/*',route=>route.request().url().startsWith(base)?route.continue():route.abort());
  await touch.goto(base+'/search-textbook.html#book-lookup');
  await touch.locator('#book-lookup-input').fill('BM25');
  await touch.locator('#book-lookup-results a').first().tap();
  assert.equal(new URL(touch.url()).hash,'#term-bm25');
  assert.ok(await touch.locator('#glossary').evaluate(e=>e.open));
  await touch.close();
  const offline=await browser.newPage();
  offline.on('pageerror',e=>errors.push(e.message));
  await offline.route('https://**/*',r=>r.abort());await offline.route('http://**/*',r=>r.abort());
  await offline.goto(pathToFileURL(path.join(root,'search-textbook.html')).href+'#book-lookup');
  await offline.locator('#book-lookup-input').fill('RRF');
  assert.equal(await offline.locator('#book-lookup-results a').first().getAttribute('href'),'#term-rrf');
  assert.deepEqual(errors,[]);
  console.log('PASS: aliases, ranking, ambiguous pooling, fragments/history, keyboard, tooltips, mobile/touch, print, no-JS and file:// lookup.');
}finally{if(browser)await browser.close();await new Promise(resolve=>server.close(resolve));}
